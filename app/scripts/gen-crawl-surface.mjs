// Generates the crawl surface — public/robots.txt and public/sitemap.xml —
// from the same category list the router uses, so adding a use case cannot
// leave the sitemap stale. Runs as `prebuild`, i.e. on every build.
//
// Both files are committed so `vite dev` serves them too; the prebuild step
// rewrites them, so any drift self-heals on the next build.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const read = (p) => readFileSync(resolve(appDir, p), 'utf8')

// Single source of truth for the canonical origin lives in seo.ts; parse it out
// rather than keeping a second copy that can drift.
const seo = read('src/lib/seo.ts')
const siteUrl = seo.match(/export const SITE_URL = '([^']+)'/)?.[1]
if (!siteUrl) throw new Error('SITE_URL not found in src/lib/seo.ts')

const categories = JSON.parse(read('src/content/categories.json'))
if (!Array.isArray(categories) || categories.length === 0) {
  throw new Error('categories.json is empty — refusing to write a sitemap with no category')
}

// Per-category `updated` when the authored content carries one, else today.
const today = new Date().toISOString().slice(0, 10)
const lastmodFor = (slug) => {
  try {
    return JSON.parse(read(`src/content/c/${slug}.json`)).updated || today
  } catch {
    return today
  }
}

// No trailing slash on category paths — that is the form <link rel="canonical">
// emits, and the two must agree or every crawl is a redirect.
const urls = [
  { loc: `${siteUrl}/`, lastmod: today },
  ...categories
    .slice()
    .sort((a, b) => a.sort - b.sort)
    .map((c) => ({ loc: `${siteUrl}/c/${c.slug}`, lastmod: lastmodFor(c.slug) })),
]

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${u.loc}</loc><lastmod>${u.lastmod}</lastmod></url>`).join('\n')}
</urlset>
`

const robots = `# Generated by scripts/gen-crawl-surface.mjs — do not edit by hand.
User-agent: *
Allow: /

Sitemap: ${siteUrl}/sitemap.xml
`

writeFileSync(resolve(appDir, 'public/sitemap.xml'), sitemap)
writeFileSync(resolve(appDir, 'public/robots.txt'), robots)
console.log(`crawl surface: ${urls.length} urls -> public/sitemap.xml, public/robots.txt`)
